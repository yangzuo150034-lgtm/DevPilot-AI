import { expect, test } from '@playwright/test'

test('demo task requires approval, exports snapshot and exposes citations', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('API 已连接')).toBeVisible()
  await page.getByRole('button', { name: '代码仓库', exact: true }).click()
  await page.getByRole('button', { name: '导入演示仓库' }).click()
  await expect(page.getByRole('button', { name: 'calculator.py', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'calculator.py', exact: true }).click()
  await expect(page.locator('.source')).toContainText('return a - b')
  await page.getByRole('button', { name: '代码检索', exact: true }).click()
  await page.getByRole('button', { name: '检索', exact: true }).click()
  await expect(page.locator('.search-results')).toContainText('calculator.py')
  await page.getByRole('button', { name: '任务工作台', exact: true }).click()
  await page.getByRole('button', { name: '创建并运行任务 →' }).click()
  await expect(page.getByRole('button', { name: '批准此补丁' })).toBeVisible()
  await expect(page.getByLabel('代码差异')).toContainText('return a + b')
  await expect(page.getByRole('button', { name: '下载补丁与快照' })).toHaveCount(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/workspace-approval.png', fullPage: true })
  await page.getByRole('button', { name: '批准此补丁' }).click()
  await expect(page.locator('.execution-panel .badge')).toHaveText('已批准 · 未验证')
  await expect(page.locator('.execution-panel')).toContainText('not_run')
  const pendingDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载补丁与快照' }).click()
  expect((await pendingDownload).suggestedFilename()).toMatch(/\.zip$/)
})

test('rejecting a proposal prevents export', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('API 已连接')).toBeVisible()
  await page.getByRole('button', { name: '创建并运行任务 →' }).click()
  await page.getByRole('button', { name: '拒绝补丁' }).click()
  await expect(page.locator('.execution-panel .badge')).toHaveText('已拒绝')
  await expect(page.getByRole('button', { name: '下载补丁与快照' })).toHaveCount(0)
})

